}

fun abbreviation(abbr: Sting): String{
    val abbrSplit = abbr.split(" ")
    val n = abbrSplit.size
    var result = ""

    for (i in 0 until n){
        result += abbrSplit[i][0].uppercase()
    }
    return result
}

fun main(){
    println(abbreviation("Министерство Тупых шуток"))
}