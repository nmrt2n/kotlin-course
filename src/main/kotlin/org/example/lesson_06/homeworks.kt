//Задание 6: "Конвертация температуры"
//
//Создайте функцию, которая конвертирует температуру из градусов Цельсия в Фаренгейты и наоборот в зависимости от указанной единицы измерения (C/F).
// Единицу измерения нужно передать вторым аргументом функции. Несколько аргументов передаются через запятую.
// Распечатай в консоль результат конвертации с добавлением единицы измерения.
// Чтобы добавить единицу измерения после результата используй функцию печати без переноса строки print("C") или print("F").

fun temperature(value: Double, unit: Char) {
    if (unit == 'C') {
        val result = value * 9 / 5 + 32
        print(result)
        print("F")
    } else if (unit == 'F') {
        val result = (value - 32) * 5 / 9
        print(result)
        print("C")
    }
}

fun main() {
    temperature(20.0, 'C')
}

//Задание 7: "Подбор одежды по погоде"
//
//Напишите функцию, которая на основе температуры воздуха рекомендует тип одежды: "куртка и шапка" при температуре ниже +10, "ветровка" от +10 до +18
// градусов включительно и "футболка и шорты" при температуре выше +18 градусов.
// При температурах ниже -30 и выше +35 рекомендуйте не выходить из дома.

fun clothes(temperature: Int) {
    when {
        temperature < -30 || temperature > 35 ->
            println("не выходить из дома")

        temperature < 10 ->
            println("куртка и шапка")

        temperature <= 18 ->
            println("ветровка")

        else ->
            println("футболка и шорты")
    }
}

fun main() {
    clothes(15)
}

//Задание 8: "Выбор фильма по возрасту"
//
//Кинотеатр предлагает фильмы разных возрастных категорий.
// апишите функцию, которая принимает возраст зрителя и возвращает доступные для него категории фильмов: "детские" (от 0 до 9), "подростковые" (от 10 до 18), "18+" для остальных.


fun movieCategory(age: Int): String {
    return when {
        age in 0..9 -> "детские"
        age in 10..18 -> "подростковые"
        else -> "18+"
    }
}

fun main() {
    println(movieCategory(15))
}